// ----------------------------------------------------------------
// PHPとの比較
// ----------------------------------------------------------------

// PHP（動的型付け）
// $x = 10;
// $x = "hello"; // OK（後から型を変えられる）

// Go（静的型付け）:= は型と変数の定義となる
x := 10
x = 20      // OK：同じint型
// x = "hello" // NG：型は一度確定したら変更不可

// ----------------------------------------------------------------
// メモ
// ----------------------------------------------------------------

// := は「宣言 + 代入」を同時に行う
// 左辺に新変数が1つ以上あれば := が使える
// 全部既存変数なら = を使う

a, err := someFunc()         // OK：a・err 両方新規
newVal, err := anotherFunc() // OK：newVal が新規、err は再代入
// a, err := yetAnotherFunc() // NG：左辺が全部既存変数 → compile error

// ----------------------------------------------------------------
// 【注意】スコープの罠
// PHPはスコープが緩いが、Goは {} 単位でスコープが厳密に分かれる
// {} 内で := を使うと、外の変数とは別の新変数が生まれる
// ----------------------------------------------------------------

err := firstFunc()

if true {
result, err := secondFunc() // このerrはif内だけの別変数！
fmt.Println(result)
}
// ここのerrはfirstFunc()のerrのまま
// secondFunc()のエラーが意図せず消える → 気づきにくいバグになる
fmt.Println(err)

// 外のerrに代入したい場合は先に宣言してから = を使う
var result string
result, err = secondFunc() // OK：両方既存変数なので =

